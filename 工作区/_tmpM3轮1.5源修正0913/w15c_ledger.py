def load(path):
    raw = open(path, 'rb').read().decode('utf-8')
    crlf = raw.count('\r\n')
    bare = raw.count('\n') - crlf
    lines = raw.split('\r\n')
    return lines, crlf, bare


def save(path, lines, crlf_before, bare_before):
    dst = path + BAK
    if os.path.exists(dst):
        print('备份已存在（＝轮1.5修前态，不覆盖；本轮增量修前态由本脚本改前转储留证），跳过：', dst)
    else:
        shutil.copy2(path, dst)
        print('备份：', dst, os.path.getsize(dst), 'bytes')
    blob = '\r\n'.join(lines)
    if blob.count('\n') - blob.count('\r\n') != bare_before:
        print('!! 裸LF数漂移（%d→%d），中止' % (bare_before, blob.count('\n') - blob.count('\r\n')))
        sys.exit(1)
    open(path, 'wb').write(blob.encode('utf-8'))
    print('写入 %s（CRLF %d→%d｜裸LF %d 不变）' % (
        os.path.basename(path), crlf_before, blob.count('\r\n'), bare_before))


def uniq(hay, needle, tag):
    c = hay.count(needle)
    if c != 1:
        print('!! 锚点非唯一（%s）命中%d：%r' % (tag, c, needle[:60]))
        sys.exit(1)


