def patch(path, anchor, new, eol):
    b = open(path, 'rb').read()
    a = anchor.encode('utf-8')
    if b.count(a) != 1:
        print('!! 锚点命中 %d 次，中止：%s' % (b.count(a), path)); sys.exit(1)
    if (new + eol).encode('utf-8') in b:
        print('!! 新行已存在，中止:', path); sys.exit(1)
    dst = path + BAK
    if not __import__('os').path.exists(dst):
        shutil.copy2(path, dst)
        print('备份：', dst)
    else:
        print('备份已存在，跳过：', dst)
    out = b.replace(a, a + eol.encode('utf-8') + new.encode('utf-8'), 1)
    open(path, 'wb').write(out)
    print('写入 %s：+%d 字节' % (path, len(out) - len(b)))


