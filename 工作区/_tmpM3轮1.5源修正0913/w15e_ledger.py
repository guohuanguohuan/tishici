def load(path):
    raw = open(path, 'rb').read().decode('utf-8')
    return raw.split('\r\n'), raw.count('\r\n'), raw.count('\n') - raw.count('\r\n')


def put(path, lines, crlf0, bare0):
    blob = '\r\n'.join(lines)
    if blob.count('\n') - blob.count('\r\n') != bare0:
        print('!! 裸LF数漂移，中止'); sys.exit(1)
    dst = path + BAK
    if os.path.exists(dst):
        print('备份已存在（＝更早修前态，不覆盖；本轮改前态见 _dump-D2-old.txt 等留证），跳过')
    else:
        shutil.copy2(path, dst); print('备份：', dst, os.path.getsize(dst), 'bytes')
    open(path, 'wb').write(blob.encode('utf-8'))
    print('写入 %s（CRLF %d→%d｜裸LF %d 不变）' % (os.path.basename(path), crlf0, blob.count('\r\n'), bare0))


def rep(lines, old, new, tag):
    blob = '\r\n'.join(lines)
    if blob.count(old) != 1:
        print('!! 锚点命中%d（应1）[%s]：%r' % (blob.count(old), tag, old[:60])); sys.exit(1)
    if new and new in blob:
        print('!! 目标文本已存在，防重跑中止 [%s]' % tag); sys.exit(1)
    print('  ✓ %s' % tag)
    return blob.replace(old, new).split('\r\n')


