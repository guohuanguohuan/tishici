def ngrams(s, n=4):
    s = "".join(ch for ch in s if not ch.isspace())
    return set(s[i:i+n] for i in range(len(s)-n+1))

def dice(a, b):
    A, B = ngrams(a), ngrams(b)
    if not A or not B:
        return 0.0
    return 2 * len(A & B) / (len(A) + len(B))

