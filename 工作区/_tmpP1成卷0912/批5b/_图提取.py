cache = {}
def imgs_of(tag):
    if tag not in cache:
        doc = Document(SRC[tag])
        body = doc.element.body
        rels = doc.part.rels
        pi = -1
        lst = []
        for child in body.iterchildren():
            kind = child.tag.split('}')[-1]
            if kind not in ('p', 'tbl'):
                continue
            pi += 1
            n = 0
            for blip in child.iter(qn('a:blip')):
                rid = blip.get(qn('r:embed'))
                if not rid or rid not in rels:
                    continue
                n += 1
                lst.append(((pi, n), rels[rid].target_part))
        cache[tag] = dict(lst)
    return cache[tag]

man = []
for key, tag, e, n, pfx, name in JOBS:
    d = imgs_of(tag)
    if (e, n) not in d:
        print('!! MISS', key, tag, e, n); continue
    part = d[(e, n)]
    data = part.blob
    ext = os.path.splitext(str(part.partname))[1].lower()
    dst = os.path.join(DST[key], f'{pfx}-{name}{ext}')
    os.makedirs(DST[key], exist_ok=True)
    open(dst, 'wb').write(data)
    tmp = dst
    try:
        with Image.open(tmp) as im:
            w, h = im.size; fmt = im.format
    except Exception:
        w = h = -1; fmt = '?'
    man.append(f"{key}\t{pfx}-{name}{ext}\t{tag}[{e}]#{n}\t{os.path.basename(str(part.partname))}\t{w}x{h}\t{fmt}\t{hashlib.md5(data).hexdigest()[:8]}")

