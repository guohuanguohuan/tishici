def norm(s: str) -> str:
    s = s.replace("\u2060", "").replace("\ufeff", "").replace("⏎", "")
    s = s.replace("⟦", "").replace("⟧", "")
    s = re.sub(r"\^\((′|')\)", "′", s)
    s = re.sub(r"\^\((°|∘)\)", "°", s)
    s = re.sub(r"\^(\([0-9]+\)|[0-9])", lambda m: m.group(1).strip("()")[-1:].translate(SUP) if len(m.group(1).strip("()"))==1 else "^"+m.group(1), s)
    s = re.sub(r"_\(([0-9]+)\)", lambda m: m.group(1).translate(SUB), s)
    s = re.sub(r"_\(([^()]{1,10})\)", r"\1", s)
    s = re.sub(r"_([0-9])", lambda m: m.group(1).translate(SUB), s)
    s = re.sub(r"√\(([0-9A-Za-z⁰¹²³₁₂₃′π/]{1,8})\)", r"√\1", s)
    s = re.sub(r"\(([^()]{1,14})\)/\(([^()]{1,14})\)", r"\1/\2", s)
    s = s.translate(FW)
    s = re.sub(r"Δ(?=[A-Z])", "△", s)  # ΔABC 系 △ 之误植字形，先于希腊→拉丁还原
    s = s.translate(str.maketrans("".join(GREEK2LAT), "".join(GREEK2LAT.values())))
    s = re.sub(r"π(?=[0-9])", "π/", s)                              # 扁平「π6」→「π/6」
    s = s.replace("﹣", "-").replace("､", "、")                      # 小连接号/顿号归一
    s = re.sub(r"(?<=[A-Za-z])1(?![0-9])", "₁", s)                  # 「A1B1C1」扁化下标还原
    s = re.sub(r"[ \t]+", " ", s)
    return s

def join_lines(block: str) -> str:
    lines = [l.rstrip() for l in block.splitlines()]
    out = []
    for l in lines:
        l = re.sub(r"^\? ?", "", l)
        l = re.sub(r"^\[[0-9]+\] ", "", l)
        if not l.strip():
            continue
        if re.match(r"^-{3,}$", l.strip()):
            continue
        l = l.strip().strip("\t")
        if out and not out[-1].endswith(("。", "；", ";", "．", ".", "：", ":", "！", "？", "，", ",")) and not re.match(r"^(（?\(?[0-9０-９]{1,2}[）)．.、]|A|B|C|D|E|F[．.]|【图】|【|①|②|③|④|⑤)", l):
            out[-1] += l
        else:
            out.append(l)
    return "\n".join(out)

def latexlin(s: str) -> str:
    """slice 源件 LaTeX 行内式线性化（仅含 \( 的文本触发）。"""
    if "\\(" not in s:
        return s
    s = re.sub(r"\\overrightarrow\{([^{}]*)\}", r"\1→", s)
    s = re.sub(r"\\vec\{([^{}]*)\}", r"\1→", s)
    s = re.sub(r"\\frac\{([^{}]*)\}\{([^{}]*)\}", r"\1/\2", s)
    s = s.replace("\\parallel", "∥").replace("\\perp", "⊥").replace("\\cdot", "·") \
         .replace("\\times", "×").replace("\\triangle", "△").replace("\\ne", "≠")
    s = re.sub(r"\\[()\[\]]", "", s)
    s = re.sub(r"(?m)^- ", "", s)
    return s

def clean(block: str) -> str:
    t = norm(join_lines(block))
    t = latexlin(t)
    t = re.sub(r"(【图】\s*){2,}", "【图】", t)
    t = re.sub(r"^\s*1\.\d\.\d(?:\.\d+)+-\d+．\s*", "", t)          # 池题头「N.N.N-N．」前缀
    t = re.sub(r"^\s*1\.\d\.\d(?:\.\d+)+-\d+\.\s*", "", t)
    t = re.sub(r"^\s*〔[^〕]{1,6}〕\s*", "", t)                      # 〔基〕/〔进〕槽位标
    t = re.sub(r"^\s*[（(](?:易|较易|简单|中档|中档偏上|难|较难)[)）]\s*", "", t)  # （难度）标
    t = re.sub(r"^\s*\d{1,2}[．.](?!\d)\s*", "", t)                  # 教材题号「N.」
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()

