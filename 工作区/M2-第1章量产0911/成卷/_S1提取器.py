def cut_ti(block: str) -> str:
    """从题块取题面段：到【答案/知识点/分析/详解/点拨】类栏头或下一题头为止。"""
    lines = block.splitlines()
    out = []
    for l in lines:
        ls = l.strip().replace("\u2060", "").replace("\xa0", " ")
        ls = re.sub(r"^\? ?", "", ls)
        ls = re.sub(r"^\[[0-9]+\]\s*", "", ls)
        if re.match(r"^(【答案|【答案思路|【知识点|【编注|【分析|【详解|【点拨|【方法|点拨|【规律|【点评|【归纳|【总结|【易错|【一题多解|【思路|【解析)", ls):
            break
        out.append(l)
    return "\n".join(out)

