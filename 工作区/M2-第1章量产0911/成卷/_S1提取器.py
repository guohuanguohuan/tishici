def parse_pool(path, pat, stop=None):
    txt = rd(path)
    els = re.findall(r"^\[(\d+)\] (.*)$", txt, re.M)
    blocks, cur = {}, None
    for num, line in els:
        line = line.strip()
        if stop and re.match(stop, line):
            cur = None
            continue
        mh = re.match(pat, line)
        if mh:
            cur = mh.group(1)
            blocks[cur] = [line]
        elif cur is not None:
            if re.match(r"^(【答案|【答案思路|【知识点|【编注|【分析|【详解|【点拨|【方法|点拨|【规律|【点评|【归纳|【总结|【易错|【一题多解|【思路|【解析)", line.strip()) \
               or re.match(pat, line) or re.match(r"^\d+题：", line) or re.match(r"^\d+\.\d+\.\d+", line) and not line.startswith(tuple("0123456789")) :
                if re.match(pat, line) or re.match(r"^\d+题：", line) or re.match(r"^\d+\.\d+\.\d+ [空本]", line):
                    cur = None
                    if re.match(pat, line):
                        mh2 = re.match(pat, line); cur = mh2.group(1); blocks[cur] = [line]
                else:
                    blocks[cur].append(line)
            else:
                blocks[cur].append(line)
    return {k: "\n".join(v) for k, v in blocks.items()}

