for full, v in rec.items():
    hit = None
    for pref, sh in SH.items():
        if full.startswith(pref):
            hit = sh
            break
    assert hit, full
    by[hit] = v
assert len(by) == 10, sorted(by)

def rng(sh):
    v = by[sh]
    return 'P%d %d–%d' % (v['part'], v['start'], v['start'] + v['pages'] - 1)

