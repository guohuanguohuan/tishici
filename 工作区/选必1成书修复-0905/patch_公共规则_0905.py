def snippet(t):
    if len(t) <= 170:
        return t
    return t[:80] + ' …… ' + t[-80:]

def apply_rules(path, rules, tag):
    s0 = io.open(path, encoding='utf-8', newline='').read()
    s = s0
    recs = []
    for name, old, new, want in rules:
        got = s.count(old)
        if got != want:
            print('ASSERT FAIL [%s] %s: count=%d want=%d' % (tag, name, got, want))
            sys.exit(1)
        s = s.replace(old, new)
        recs.append((name, old, new, got))
    # 括号/引号不平衡量保持（原文固有 902/898 等，不许因本手术变化）
    for a, b in [('（', '）'), ('「', '」'), ('〔', '〕')]:
        d0 = s0.count(a) - s0.count(b)
        d1 = s.count(a) - s.count(b)
        if d0 != d1:
            print('BALANCE FAIL [%s] %s%s: before=%d after=%d' % (tag, a, b, d0, d1))
            sys.exit(1)
    io.open(path, 'w', encoding='utf-8', newline='').write(s)
    return s0, s, recs

