    data = {
        'R': io.open(RULE, encoding='utf-8', newline='').read(),
        'Z': io.open(ZK, encoding='utf-8', newline='').read(),
    }
    orig = {k: len(v) for k, v in data.items()}
    # 记录原始行号（按原始文件）
    orig_lines = {k: v.split('\r\n') for k, v in data.items()}
    log = []
    # 先全部断言唯一命中
    errs = []
    for i, (fk, cat, old, new, why) in enumerate(E, 1):
        c = data[fk].count(old)
        if c != 1:
            errs.append((i, fk, c, old[:60]))
            continue
        # 定位行号
        ln = None
        for j, l in enumerate(orig_lines[fk], 1):
            if old in l:
                ln = j
                break
        log.append((i, fk, ln, cat, len(old), len(new), why))
    if errs:
        print('断言失败（未唯一命中），不落盘：')
        for i, fk, c, frag in errs:
            print('  #%d file=%s count=%d old=%s…' % (i, fk, c, frag))
        sys.exit(1)
    for i, (fk, cat, old, new, why) in enumerate(E, 1):
        data[fk] = data[fk].replace(old, new, 1)
    dR = len(data['R']) - orig['R']
    dZ = len(data['Z']) - orig['Z']
    print('公共规则.md: %d → %d（净减 %d）' % (orig['R'], len(data['R']), -dR))
    print('高中同步总控.md: %d → %d（净减 %d）' % (orig['Z'], len(data['Z']), -dZ))
    # 分类统计
    from collections import defaultdict
    stat = defaultdict(lambda: [0, 0])
    for i, fk, ln, cat, lo, lnw, why in log:
        stat[cat][0] += 1
        stat[cat][1] += lo - lnw
    for cat, (n, d) in stat.items():
        print('  %s: %d 处，净减 %d 字符' % (cat, n, d))
    if not apply:
        print('（干跑，未落盘；确认后加 apply 参数执行）')
        return
    io.open(RULE, 'w', encoding='utf-8', newline='').write(data['R'])
    io.open(ZK, 'w', encoding='utf-8', newline='').write(data['Z'])
    # 行数结构核验
    r2 = io.open(RULE, encoding='utf-8', newline='').read()
    z2 = io.open(ZK, encoding='utf-8', newline='').read()
    assert len(r2.split('\r\n')) == len(orig_lines['R']), '公共规则行数变化！'
    assert len(z2.split('\r\n')) == len(orig_lines['Z']), '总控行数变化！'
    print('行数结构核验通过：公共规则 %d 行、总控 %d 行（均不变）' % (len(orig_lines['R']), len(orig_lines['Z'])))
