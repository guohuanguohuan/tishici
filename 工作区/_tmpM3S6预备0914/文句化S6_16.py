for path, edits, name in ((F16, E16, "课时16"), (F17, E17, "课时17")):
    s = io.open(path, encoding="utf-8").read()
    miss = []
    for old, new in edits:
        c = s.count(old)
        if c != 1:
            miss.append((c, old[:70]))
            continue
        s = s.replace(old, new)
    if miss:
        print(name, "异常项：")
        for c, frag in miss:
            print("  count=%d :: %s" % (c, frag))
        raise SystemExit(1)
    io.open(path, "w", encoding="utf-8", newline="").write(s)
    # 残留扫描（剔注释）
    code = "\n".join(l.split("%")[0] for l in s.split("\n"))
    rest = len(re.findall(r"ding\{", code)) + len(re.findall(r"Rightarrow", code)) + len(re.findall(r"iff", code))
    print("%s：%d 处替换落盘，印面残留 ding/⇒/⟺ ＝ %d（应为 0）" % (name, len(edits), rest))
print("done")
