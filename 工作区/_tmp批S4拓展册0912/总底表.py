def build_jobs():
    jobs = []
    for r in ROWS:
        tid, src = r[0], r[5]
        if not src: continue
        doc, key = src
        if isinstance(key, list):
            jobs.append({'id': 't%03d' % tid, 'doc': doc, 'range': key})
        else:
            jobs.append({'id': 't%03d' % tid, 'doc': doc, 'range': None, 'qnum': key})
    return jobs

