# 片G · sub3 逐要素位移诊断：在指定源-px 窗口内比较「源墨迹质心」与「重绘墨迹质心」，输出 Δx,Δy（源−重绘）
# 用法：python sub3_diff.py
import numpy as np
from PIL import Image

S = 1.0
src = np.array(Image.open("sub3_source.png").convert("L")).astype(float) / 255.0 < 0.5
red = np.array(Image.open("sub3_render1x.png").convert("L")).astype(float) / 255.0 < 0.5

W = [
    # 名称, x0,y0,x1,y1（源 px 窗口）
    ("①平面α",        10, 130, 440, 300),
    ("①自由a线",       55,  55, 215, 150),
    ("①链A",           60, 150, 130, 240),
    ("①水平基线",     120, 232, 292, 250),
    ("①面内a",        200, 160, 275, 245),
    ("①标签a(上)",    112,  55, 150, 100),
    ("①标签a(内)",    168, 155, 205, 200),
    ("①标签c",        132, 245, 168, 292),
    ("①标签b",        215, 240, 250, 295),
    ("①标签α",        340, 160, 375, 192),
    ("①圈①",         130, 315, 185, 370),
    ("②平面α",       500, 130, 915, 300),
    ("②自由a线",      545,  50, 705, 150),
    ("②直线l",        580, 232, 782, 248),
    ("②面内a",        688, 155, 760, 245),
    ("②标签α",        835, 150, 870, 182),
    ("②标签l",        782, 210, 805, 255),
    ("②圈②",         625, 315, 680, 370),
    ("③平面β",        985, 130, 1400, 300),
    ("③自由a线",     1110,  35, 1270, 125),
    ("③竖A-A'",      1108, 128, 1136, 195),
    ("③竖B-B'",      1252,  40, 1276, 190),
    ("③A'B'线",      1112, 180, 1265, 198),
    ("③中斜虚线",    1125, 100, 1262, 188),
    ("③标签A",       1080,  85, 1115, 125),
    ("③标签B",       1265,   8, 1300,  48),
    ("③标签A'",      1082, 193, 1130, 235),
    ("③标签B'",      1242, 194, 1290, 235),
    ("③标签a(上)",   1165,  25, 1200,  68),
    ("③标签a(中)",   1192, 143, 1226, 187),
    ("③标签c",       1183, 190, 1216, 234),
    ("③标签β",       1315, 145, 1352, 196),
    ("③圈③",        1115, 315, 1170, 370),
]
print(f"{'要素':<14}{'源质心(px)':>18}{'重绘质心(px)':>18}{'Δ源-绘(px)':>16}{'Δmm':>14}")
for name, x0, y0, x1, y1 in W:
    a = (int(x0 * S), int(y0 * S), int(x1 * S), int(y1 * S))
    sl = (slice(a[1], a[3]), slice(a[0], a[2]))
    s, r = src[sl], red[sl]
    if s.sum() == 0 or r.sum() == 0:
        print(f"{name:<14}  -- 源{s.sum()} 绘{r.sum()} --")
        continue
    ys, xs = np.nonzero(s); yr, xr = np.nonzero(r)
    cs = np.array([xs.mean(), ys.mean()]); cr = np.array([xr.mean(), yr.mean()])
    d = (cr - cs) / S        # 换算回源 px（正=重绘偏右下）
    print(f"{name:<14}{str(np.round(cs,1)):>18}{str(np.round(cr,1)):>18}{str(np.round(d,2)):>16}"
          f"{'  (%.2f,%.2f)' % (d[0]*0.0610796, d[1]*0.0610796):>14}  源{s.sum():5d} 绘{r.sum():5d}")
