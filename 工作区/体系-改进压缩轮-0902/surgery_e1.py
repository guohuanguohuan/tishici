def main():
    text = io.open(SRC, encoding="utf-8").read()
    before_len = len(text)
    log = []
    cur = text
    for tag, old, new in REPL:
        c = cur.count(old)
        if c != 1:
            log.append(f"{tag}: ABORT count={c} old={old!r}")
            continue
        cur = cur.replace(old, new, 1)
        log.append(f"{tag}: OK net={len(new)-len(old)} count(old)@apply=1")
    io.open(SRC, "w", encoding="utf-8", newline="").write(cur)
    after_len = len(cur)
    print("\n".join(log))
    print(f"len_before={before_len} len_after={after_len} delta={after_len-before_len}")
    assert after_len <= 50000, "预算超限"


if __name__ == "__main__":
    main()
