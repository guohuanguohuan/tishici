#   #18 真正意图的三处微调＝第一个→首个、段落→段、本节成卷自检→成卷自检（净-4，与规格书验收合计一致），
#   故以精确子串「其后第一个非标题段落必须是该组合的题，见本节成卷自检」（count=1）为替换串照抄改后。
