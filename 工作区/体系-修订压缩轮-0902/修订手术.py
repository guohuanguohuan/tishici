# 第一遍：全量断言（不写盘）
texts, errs = {}, []
for fn, edits in EDITS.items():
    t = open(R+'\\'+fn, encoding='utf-8').read()
    for old, new in edits:
        c = t.count(old)
        if c != 1:
            errs.append(f'{fn}: count={c} ← {old[:40]}…')
        if old == new:
            errs.append(f'{fn}: old==new ← {old[:30]}…')
    texts[fn] = t
if errs:
    print('断言失败，未写任何文件：')
    [print(' ', e) for e in errs]
    sys.exit(1)

# 第二遍：替换并写盘
for fn, edits in EDITS.items():
    t = texts[fn]
    for old, new in edits:
        assert t.count(old) == 1
        t = t.replace(old, new)
    open(R+'\\'+fn, 'w', encoding='utf-8', newline='').write(t)
    print(f'{fn}: {len(edits)}处已写')

# 第三遍：复验——旧串零残留、新串在位、预算实测
